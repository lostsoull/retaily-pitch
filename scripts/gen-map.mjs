// Generates src/assets/mapData.ts: projected SVG paths for the market slide.
// Run: node scripts/gen-map.mjs
//
// Morocco is drawn as ONE territory: Natural Earth's "W. Sahara" (732) is merged into
// Morocco (504) with no internal border.
import { readFileSync, writeFileSync } from 'node:fs'
import { geoBounds, geoMercator, geoPath, geoContains } from 'd3-geo'
import { feature, merge } from 'topojson-client'

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'))
const geoms = topo.objects.countries.geometries
const all = feature(topo, topo.objects.countries).features

const MOROCCO = ['504', '732']
const morocco = { type: 'Feature', properties: {}, geometry: merge(topo, geoms.filter((g) => MOROCCO.includes(String(g.id)))) }

// Region framing: West Africa to the Gulf.
// (Corner points, not a polygon: a polygon's winding decides inside/outside in d3-geo.)
const regionBox = { type: 'MultiPoint', coordinates: [[-20, -7], [62, 40]] }
const W = 2000
const H = 1400
const projection = geoMercator().fitSize([W, H], regionBox)
const path = geoPath(projection).digits(1)

// Highlight groups for "the same playbook, next".
const MENA = ['012', '788', '434', '818', '478', '682', '784', '634', '414', '048', '512', '400', '422', '368']
const FRANCO = ['686', '466', '384', '854', '324', '562', '204', '768', '120', '266', '178', '180', '148', '140']

const inView = (f) => {
  const [[lon0, lat0], [lon1, lat1]] = geoBounds(f)
  if (lon1 < lon0) return false // crosses the antimeridian: far away
  return lon1 > -26 && lon0 < 66 && lat1 > -12 && lat0 < 46
}

const countries = all
  .filter((f) => !MOROCCO.includes(String(f.id)) && inView(f))
  .map((f) => ({
    id: String(f.id),
    name: f.properties.name,
    group: MENA.includes(String(f.id)) ? 'mena' : FRANCO.includes(String(f.id)) ? 'franco' : 'base',
    d: path(f),
  }))
  .filter((c) => c.d)

const CITIES = [
  ['Casablanca', 33.57, -7.59, 40],
  ['Rabat', 34.02, -6.84, 16],
  ['Marrakech', 31.63, -8.01, 16],
  ['Fès', 34.03, -5.0, 14],
  ['Tanger', 35.76, -5.83, 14],
  ['Agadir', 30.43, -9.6, 10],
  ['Meknès', 33.9, -5.55, 8],
  ['Oujda', 34.68, -1.91, 7],
  ['Kénitra', 34.26, -6.58, 6],
  ['Tétouan', 35.57, -5.37, 6],
  ['Béni Mellal', 32.34, -6.36, 5],
  ['Nador', 35.17, -2.93, 4],
  ['Laâyoune', 27.15, -13.2, 3],
  ['Dakhla', 23.72, -15.94, 2],
]
const LABELLED = ['Casablanca', 'Rabat', 'Marrakech', 'Fès', 'Tanger', 'Agadir', 'Oujda', 'Laâyoune', 'Dakhla']

const cities = CITIES.map(([name, lat, lon]) => {
  const [x, y] = projection([lon, lat])
  return { name, x: +x.toFixed(1), y: +y.toFixed(1), label: LABELLED.includes(name) }
})

// Deterministic merchant dots, clustered around cities, kept inside Morocco.
let seed = 7
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647)
const gauss = () => Math.sqrt(-2 * Math.log(rnd() + 1e-9)) * Math.cos(2 * Math.PI * rnd())
const total = CITIES.reduce((s, c) => s + c[3], 0)
const dots = []
for (const [, lat, lon, w] of CITIES) {
  const n = Math.round((w / total) * 320)
  let made = 0
  let tries = 0
  while (made < n && tries < n * 60) {
    tries++
    const spread = 0.25 + w / 60
    const p = [lon + gauss() * spread, lat + gauss() * spread * 0.8]
    if (!geoContains(morocco, p)) continue
    const [x, y] = projection(p)
    dots.push([+x.toFixed(1), +y.toFixed(1)])
    made++
  }
}

// View boxes (aspect matched to the 1100 x 960 map frame on stage).
const FRAME = 1100 / 960
const fitBox = ([[x0, y0], [x1, y1]], pad) => {
  let w = x1 - x0 + pad * 2
  let h = y1 - y0 + pad * 2
  const cx = (x0 + x1) / 2
  const cy = (y0 + y1) / 2
  if (w / h > FRAME) h = w / FRAME
  else w = h * FRAME
  return [+(cx - w / 2).toFixed(1), +(cy - h / 2).toFixed(1), +w.toFixed(1), +h.toFixed(1)]
}
const vbMorocco = fitBox(path.bounds(morocco), 18)
const vbRegion = fitBox([[0, 0], [W, H]], 0)

const out = {
  morocco: geoPath(projection).digits(2)(morocco),
  countries,
  cities,
  dots,
  vbMorocco,
  vbRegion,
}
writeFileSync(
  'src/assets/mapData.ts',
  `// Generated by scripts/gen-map.mjs from world-atlas (Natural Earth 1:50m). Do not edit.\n` +
    `// Morocco includes its Sahara as one territory.\n` +
    `export const MAP = ${JSON.stringify(out)} as const\n`,
)
console.log('countries', countries.length, 'dots', dots.length, 'bytes', JSON.stringify(out).length, vbMorocco, vbRegion)
